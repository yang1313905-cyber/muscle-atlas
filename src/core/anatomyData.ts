type StretchDose = [sets: number, seconds: number];

function stretch(
  source: StretchItem['source'],
  doses: [StretchDose, StretchDose, StretchDose],
) {
  const formatDose = ([sets, seconds]: StretchDose) => `${sets} 组 × ${seconds} 秒`;
  return (
    id: string,
    nameZh: string,
    targetMuscles: DetailedMuscleId[],
    secondaryMuscles: DetailedMuscleId[],
    setup: string,
    execution: string,
    caution: string,
    benefit: string,
  ): StretchItem => ({
    id, nameZh, targetMuscles, secondaryMuscles, source, setup, execution, caution, benefit,
    dosage: {
      beginner: formatDose(doses[0]),
      intermediate: formatDose(doses[1]),
      advanced: formatDose(doses[2]),
    },
  });
}

