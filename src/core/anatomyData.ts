type SourceMuscle = JointActionEntry['sourceMuscles'][number];

function muscle(
  nameZh: string,
  mappedMuscleIds?: DetailedMuscleId[],
  qualifier?: string,
): SourceMuscle {
  return { nameZh, mappedMuscleIds, qualifier };
}

function joint(
  jointZh: string,
  jointAnatomicalZh: string,
  fitnessCore: boolean,
  sourceIsSummary = false,
) {
  return (
    id: string,
    actionZh: string,
    antagonistActionZh: string | undefined,
    sourceMuscles: SourceMuscle[],
    errataNote?: string,
  ): JointActionEntry => ({
    id,
    jointZh,
    jointAnatomicalZh,
    actionZh,
    antagonistActionZh,
    fitnessCore,
    sourceMuscles,
    errataNote: [
      sourceIsSummary && '审校稿仅列活动摘要，参与肌肉按标准解剖补录。',
      errataNote,
    ].filter(Boolean).join('') || undefined,
  });
}

