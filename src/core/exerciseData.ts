import type { DetailedMuscleId, Exercise, ExerciseMuscleLink, MuscleRole } from './types';

type MuscleScore = [muscleId: DetailedMuscleId, effectiveness: number];

// Scores rank exercise fit within this catalog. They are not measured EMG percentages.
function roles(
  primary: MuscleScore[],
  secondary: MuscleScore[] = [],
  stabilizer: MuscleScore[] = [],
): ExerciseMuscleLink[] {
  const links = (scores: MuscleScore[], role: MuscleRole) =>
    scores.map(([muscleId, effectiveness]) => ({ muscleId, role, effectiveness }));
  return [
    ...links(primary, 'primary'),
    ...links(secondary, 'secondary'),
    ...links(stabilizer, 'stabilizer'),
  ];
}

function exercise(entry: Omit<Exercise, 'media' | 'aliases'> & { aliases?: string[] }): Exercise {
  return {
    ...entry,
    aliases: entry.aliases ?? [],
    media: { videoSearchQuery: `${entry.nameZh} ${entry.nameEn} 动作教学` },
  };
}

